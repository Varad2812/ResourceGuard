import { Check, Dice5, Download, FileJson, Minus, Plus, RotateCcw, Upload, AlertTriangle } from 'lucide-react';
import { useEffect, useMemo, useRef, useState } from 'react';
import { MatrixTable, VectorRow } from '../components/Matrix';
import { Badge, Button, Card, CSourceNote, Label, PageHeader, Skeleton } from '../components/ui';
import { useEngine, useStore } from '../lib/store';
import type { SysState } from '../lib/types';
import { cx, dims, download, errorCells, sameState, toSys } from '../lib/util';

function useDebounced<T>(v: T, ms: number) {
  const [d, setD] = useState(v);
  useEffect(() => {
    const t = setTimeout(() => setD(v), ms);
    return () => clearTimeout(t);
  }, [v, ms]);
  return d;
}

function parseImported(text: string): SysState {
  const raw = JSON.parse(text);
  const s = raw?.state ?? raw;
  if (!Array.isArray(s?.allocation) || !Array.isArray(s?.max) || !Array.isArray(s?.available)) {
    throw new Error('JSON must contain allocation, max and available arrays');
  }
  return toSys(s);
}

export default function Editor() {
  const { state, commit, run, toast, scenarios, loadScenario, scenarioId } = useStore();
  const [draft, setDraft] = useState<SysState>(() => toSys(state));
  const [rand, setRand] = useState({ P: 6, R: 4, seed: 42, safe: true });
  const [paste, setPaste] = useState('');
  const fileRef = useRef<HTMLInputElement>(null);

  useEffect(() => setDraft(toSys(state)), [state]);

  const debounced = useDebounced(draft, 220);
  const key = JSON.stringify(debounced);
  const { data: check, loading } = useEngine({ action: 'safety', state: debounced }, key);
  const { P, R } = dims(draft);
  const cells = useMemo(() => errorCells(check?.errors ?? []), [check]);
  const dirty = !sameState(draft, state);
  const stale = key !== JSON.stringify(draft);
  const valid = !!check?.ok && !stale;

  const set = (m: 'allocation' | 'max', i: number, j: number, v: number) =>
    setDraft((d) => ({ ...d, [m]: d[m].map((row, a) => (a === i ? row.map((x, b) => (b === j ? v : x)) : row)) }));
  const setAvail = (j: number, v: number) => setDraft((d) => ({ ...d, available: d.available.map((x, b) => (b === j ? v : x)) }));

  const addProcess = () => P < 20 && setDraft((d) => ({ ...d, allocation: [...d.allocation, Array(R).fill(0)], max: [...d.max, Array(R).fill(0)] }));
  const removeProcess = (i: number) => P > 1 && setDraft((d) => ({ ...d, allocation: d.allocation.filter((_, a) => a !== i), max: d.max.filter((_, a) => a !== i) }));
  const addResource = () =>
    R < 10 && setDraft((d) => ({ allocation: d.allocation.map((r) => [...r, 0]), max: d.max.map((r) => [...r, 0]), available: [...d.available, 0] }));
  const removeResource = () =>
    R > 1 && setDraft((d) => ({ allocation: d.allocation.map((r) => r.slice(0, -1)), max: d.max.map((r) => r.slice(0, -1)), available: d.available.slice(0, -1) }));

  const apply = () => {
    if (!valid || !check) return;
    commit({ kind: 'edit', label: `Edited state (${P}×${R})`, state: draft, result: check, decision: check.decision });
    toast('State applied', check.safe ? 'safe' : 'unsafe', `C engine reports ${check.decision}`);
  };

  const randomize = async () => {
    try {
      const r = await run({ action: 'random', processes: rand.P, resources: rand.R, seed: rand.seed, ensure_safe: rand.safe });
      if (!r.ok || !r.state) throw new Error(r.errors.join('; '));
      setDraft(toSys(r.state));
      setRand((x) => ({ ...x, seed: x.seed + 1 }));
      toast(`Random ${rand.P}×${rand.R} state generated by C`, r.safe ? 'safe' : 'unsafe', `seed ${rand.seed} · ${r.decision} · press Apply to use it`);
    } catch (e) {
      toast('Random generation failed', 'unsafe', String(e));
    }
  };

  const importText = (text: string) => {
    try {
      setDraft(parseImported(text));
      toast('JSON imported into the draft', 'primary', 'Check validation, then Apply');
    } catch (e) {
      toast('Import failed', 'unsafe', e instanceof Error ? e.message : String(e));
    }
  };

  const sameDims = state.allocation.length === P && state.available.length === R;
  const tone = (m: 'alloc' | 'max', i: number, j: number) => {
    if (cells.has(`${m}:${i}:${j}`)) return 'error' as const;
    const before = m === 'alloc' ? state.allocation : state.max;
    const now = m === 'alloc' ? draft.allocation : draft.max;
    return sameDims && before[i][j] !== now[i][j] ? ('changed' as const) : undefined;
  };

  return (
    <>
      <PageHeader title="State Editor" kicker="Model the system">
        <Badge tone={stale || loading ? 'neutral' : valid ? (check?.safe ? 'safe' : 'unsafe') : 'unsafe'} dot>
          {stale || loading ? 'Validating in C…' : valid ? `Valid · ${check?.safe ? 'Safe' : 'Unsafe'}` : 'Invalid'}
        </Badge>
        <Button variant="ghost" onClick={() => setDraft(toSys(state))} disabled={!dirty}>
          <RotateCcw size={14} /> Reset
        </Button>
        <Button variant="primary" onClick={apply} disabled={!dirty || !valid}>
          <Check size={14} /> Apply to simulator
        </Button>
      </PageHeader>

      <div className="grid grid-cols-12 items-start gap-3">
        <Card
          className="col-span-12 xl:col-span-9"
          title="Matrices"
          subtitle="Edit Allocation, Max and Available. Need = Max − Allocation is recomputed by the C engine on every keystroke."
          actions={
            <>
              <Button size="sm" onClick={addProcess} disabled={P >= 20}>
                <Plus size={13} /> Process
              </Button>
              <Button size="sm" onClick={addResource} disabled={R >= 10}>
                <Plus size={13} /> Resource
              </Button>
              <Button size="sm" variant="ghost" onClick={removeResource} disabled={R <= 1} title="Remove last resource type">
                <Minus size={13} /> R{R - 1}
              </Button>
            </>
          }
        >
          <div className="grid gap-3 lg:grid-cols-3">
            <MatrixTable
              title="Allocation"
              data={draft.allocation}
              editable
              onChange={(i, j, v) => set('allocation', i, j, v)}
              cellToneFn={(i, j) => tone('alloc', i, j)}
              rowSuffix={(i) => (
                <button aria-label={`Remove P${i}`} title={`Remove P${i}`} disabled={P <= 1} onClick={() => removeProcess(i)} className="text-muted/60 hover:text-unsafe disabled:opacity-30">
                  <Minus size={12} />
                </button>
              )}
            />
            <MatrixTable title="Max" data={draft.max} editable onChange={(i, j, v) => set('max', i, j, v)} cellToneFn={(i, j) => tone('max', i, j)} />
            {valid && check?.state ? (
              <MatrixTable title="Need (from C)" accent data={check.state.need} cellToneFn={(i, j) => (check.state!.need[i][j] === 0 ? 'dim' : undefined)} />
            ) : (
              <div>
                <div className="mb-1 font-display text-[13px] font-semibold text-primary">Need (from C)</div>
                {stale || loading ? (
                  <Skeleton className="h-full min-h-[140px]" />
                ) : (
                  <div className="flex min-h-[140px] items-center justify-center rounded-lg border border-dashed border-unsafe/40 bg-unsafe/5 p-3 text-center text-xs text-unsafe">
                    Need is not computed for an invalid state. Fix the highlighted cells.
                  </div>
                )}
              </div>
            )}
          </div>
          <div className="mt-4 flex flex-wrap items-end justify-between gap-3 border-t border-line/70 pt-3">
            <VectorRow label="Available" data={draft.available} editable onChange={setAvail} toneFn={(j) => (cells.has(`avail:${j}`) ? 'error' : undefined)} />
            {valid && check?.state && <VectorRow label="Total (C)" data={check.state.total} />}
          </div>
        </Card>

        <div className="col-span-12 flex flex-col gap-3 xl:col-span-3">
          <Card title="Validation" icon={<AlertTriangle size={14} />}>
            {check && !stale ? (
              check.ok ? (
                <div className="space-y-1.5 text-xs">
                  <div className="flex items-center gap-2 text-safe">
                    <Check size={14} /> Allocation ≤ Max, no negatives, sizes OK
                  </div>
                  <div className={cx('flex items-center gap-2', check.safe ? 'text-safe' : 'text-unsafe')}>
                    {check.safe ? <Check size={14} /> : <AlertTriangle size={14} />}
                    {check.safe ? `Safe: ⟨${check.safety?.sequence.map((p) => `P${p}`).join(' ')}⟩` : 'Unsafe: no safe sequence exists'}
                  </div>
                  <div className="pt-1">
                    <CSourceNote action="safety" ops={check.ops} />
                  </div>
                </div>
              ) : (
                <ul className="max-h-48 space-y-1 overflow-y-auto text-xs text-unsafe scroll-thin">
                  {check.errors.map((e) => (
                    <li key={e} className="rounded-md bg-unsafe/10 px-2 py-1 font-mono">
                      {e}
                    </li>
                  ))}
                </ul>
              )
            ) : (
              <Skeleton className="h-10" />
            )}
          </Card>

          <Card title="Presets" subtitle="Load a scenario onto the timeline">
            <div className="grid grid-cols-1 gap-1.5">
              {scenarios.map((s) => (
                <button
                  key={s.id}
                  onClick={() => loadScenario(s.id)}
                  className={cx(
                    'rounded-lg border px-2.5 py-1.5 text-left transition hover:border-primary/50',
                    scenarioId === s.id ? 'border-primary/50 bg-primary/5' : 'border-line bg-sunk/40',
                  )}
                >
                  <div className="flex items-center justify-between text-[13px] font-semibold">
                    {s.name}
                    {s.tag && <span className="text-[10px] font-medium text-muted">{s.tag}</span>}
                  </div>
                </button>
              ))}
            </div>
          </Card>

          <Card title="Random generator" subtitle="Seeded generator in C" icon={<Dice5 size={14} />}>
            <div className="grid grid-cols-3 gap-2">
              {(['P', 'R', 'seed'] as const).map((k) => (
                <label key={k} className="block">
                  <Label>{k === 'P' ? 'Procs' : k === 'R' ? 'Res.' : 'Seed'}</Label>
                  <input
                    className="input h-8 w-full font-mono"
                    type="number"
                    min={1}
                    max={k === 'P' ? 20 : k === 'R' ? 10 : 99999}
                    value={rand[k]}
                    onChange={(e) => setRand((x) => ({ ...x, [k]: Number(e.target.value) || 1 }))}
                  />
                </label>
              ))}
            </div>
            <label className="mt-2 flex items-center gap-2 text-xs text-muted">
              <input type="checkbox" checked={rand.safe} onChange={(e) => setRand((x) => ({ ...x, safe: e.target.checked }))} className="accent-[rgb(var(--primary))]" />
              Guarantee a safe state
            </label>
            <Button className="mt-2 w-full" onClick={randomize}>
              <Dice5 size={14} /> Generate into draft
            </Button>
          </Card>

          <Card title="Import / export" icon={<FileJson size={14} />}>
            <div className="flex gap-2">
              <Button size="sm" className="flex-1" onClick={() => fileRef.current?.click()}>
                <Upload size={13} /> Import file
              </Button>
              <Button size="sm" className="flex-1" onClick={() => download('resourceguard-state.json', JSON.stringify({ state: draft }, null, 2), 'application/json')}>
                <Download size={13} /> Export
              </Button>
            </div>
            <input
              ref={fileRef}
              type="file"
              accept="application/json,.json"
              className="hidden"
              onChange={async (e) => {
                const f = e.target.files?.[0];
                if (f) importText(await f.text());
                e.target.value = '';
              }}
            />
            <textarea
              value={paste}
              onChange={(e) => setPaste(e.target.value)}
              placeholder='Paste {"allocation":[[…]],"max":[[…]],"available":[…]}'
              className="input mt-2 h-20 w-full resize-none py-1.5 font-mono text-[11px]"
            />
            <Button size="sm" variant="ghost" className="w-full" disabled={!paste.trim()} onClick={() => importText(paste)}>
              Load pasted JSON
            </Button>
          </Card>
        </div>
      </div>
    </>
  );
}
